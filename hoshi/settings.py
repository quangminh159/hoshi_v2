def _redis_reachable(url: str) -> bool:
    if not url:
        return False
    try:
        import redis
        client = redis.Redis.from_url(url, socket_connect_timeout=1, socket_timeout=1)
        client.ping()
        client.close()
        return True
    except Exception:
        return False


