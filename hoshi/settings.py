def _aws_looks_real(value: str) -> bool:
    v = (value or '').strip()
    if not v:
        return False
    low = v.lower()
    if low.startswith('your-') or low in {
        'changeme',
        'todo',
        'xxx',
        'your-aws-access-key',
        'your-aws-secret-key',
        'your-bucket-name',
        'your-region',
    }:
        return False
    return True


